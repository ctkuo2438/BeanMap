export const LANGUAGE_STORAGE_KEY = 'beanmap.language';

export const languages = [
  { id: 'zh-Hant', label: '繁中', accessibleLabel: '繁體中文' },
  { id: 'en', label: 'English', accessibleLabel: 'English' },
];

export function getInitialLanguage() {
  try {
    const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (languages.some(language => language.id === saved)) return saved;
  } catch {
    // Browsing and switching languages still work when storage is unavailable.
  }
  return 'zh-Hant';
}

